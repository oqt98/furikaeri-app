export type TranslationKey = keyof (typeof messages)['ja'];

export function getLocaleTag(locale: AppLocale) {
  return locale === 'ja' ? 'ja-JP' : 'en-US';
}

export function translate(
  locale: AppLocale,
  key: TranslationKey,
  params?: Record<string, string | number>
) : string {
  const template = String(messages[locale][key] ?? messages.ja[key]);
  if (!params) return template;

  return Object.entries(params).reduce<string>(
    (current, [paramKey, value]) =>
      current.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(value)),
    template
  );
}
